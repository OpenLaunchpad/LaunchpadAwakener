import CoreGraphics
import Foundation
import ObjCRuntimeToolbox
import OSToolbox
import QuartzCore
import LaunchpadAwakenerSpringboardCore

/// One Dock method the payload calls, with the signature the call was written against.
struct DockMethodSignature: Sendable {
    let className: String
    let selectorName: String
    /// Derived by `@RuntimeClassProxy` from the Swift declaration of the call, or, for a method the payload
    /// calls some other way, read from the Dock's Objective-C metadata — never from a decompiler. Frame
    /// offsets are ignored by the comparison.
    let typeEncoding: String

    var selector: Selector {
        NSSelectorFromString(selectorName)
    }

    /// The methods a proxy generated by `@RuntimeClassProxy` calls, with the signatures it checks itself.
    static func signatures(
        ofClassNamed className: String,
        requirements: [RuntimeClassProxySupport.MethodRequirement]
    ) -> [DockMethodSignature] {
        requirements.map { requirement in
            DockMethodSignature(
                className: className,
                selectorName: NSStringFromSelector(requirement.selector),
                typeEncoding: requirement.typeEncoding
            )
        }
    }
}

/// `WALayerKitWindow`, the Dock's own window class; made by
/// ``DockHostInterface/makeLayerKitWindow(frame:connectionIdentifier:displayIdentifier:tags:level:)``.
@RuntimeClassProxy("WALayerKitWindow")
protocol DockLayerKitWindow {
    var layer: CALayer? { get }
    /// The window server's identifier for the window.
    var wid: UInt32? { get }
    /// `ordering` follows the window server: 1 orders above every other window at the same level, 0 orders out.
    func order(_ ordering: Int32, otherWindow: UInt32)
}

/// Every call from the payload into the Dock's own classes goes through here.
///
/// A call with a wrong signature puts arguments in the wrong registers inside someone else's process,
/// so each method is checked against the live Dock once, before any hook is installed: if one does
/// not match, the payload installs nothing and the Dock keeps its own behaviour. Most calls go through
/// `@RuntimeClassProxy` proxies, whose signatures are derived from their Swift declarations and listed
/// here from the proxies themselves.
@Loggable(subsystem: "com.MxIris.LaunchpadAwakener", category: "DockHostInterface")
enum DockHostInterface {
    // MARK: - Signatures

    /// `-[WALayerKitWindow initWithFrame:connection:display:tags:level:]`, what macOS 15's
    /// `-[Springboard init]` created its window with.
    static let layerKitWindowInitialiser = DockMethodSignature(
        className: "WALayerKitWindow",
        selectorName: "initWithFrame:connection:display:tags:level:",
        typeEncoding: "@68@0:8{CGRect={CGPoint=dd}{CGSize=dd}}16I48I52Q56i64"
    )

    static let requiredMethods: [DockMethodSignature] = [layerKitWindowInitialiser]
        + DockMethodSignature.signatures(
            ofClassNamed: DockLayerKitWindowImplementation.runtimeClassName,
            requirements: DockLayerKitWindowImplementation.methodRequirements
        )
        + DockLayerFactory.requiredMethods
        + DockEnvironment.requiredMethods

    /// Whether every method the payload calls exists with the expected signature.
    ///
    /// Logs the live encoding of each mismatch, so a system update can be adapted to from the log alone.
    static let isCompatible: Bool = checkRequiredMethods()

    private static func checkRequiredMethods() -> Bool {
        var mismatchCount = 0
        for requiredMethod in requiredMethods {
            let isMatching = RuntimeMethodInspector.hasMethod(
                className: requiredMethod.className,
                selector: requiredMethod.selector,
                matchingTypeEncoding: requiredMethod.typeEncoding
            )
            guard !isMatching else { continue }
            mismatchCount += 1
            let liveTypeEncoding = RuntimeMethodInspector.typeEncoding(
                forClassNamed: requiredMethod.className,
                selector: requiredMethod.selector
            )
            #log(.error, "-[\(requiredMethod.className, privacy: .public) \(requiredMethod.selectorName, privacy: .public)] expected \(requiredMethod.typeEncoding, privacy: .public), found \(liveTypeEncoding ?? "nothing", privacy: .public)")
        }
        #log(.info, "Checked \(requiredMethods.count, privacy: .public) Dock method(s), \(mismatchCount, privacy: .public) mismatch(es)")
        return mismatchCount == 0
    }

    // MARK: - WALayerKitWindow

    /// Creates a window on `connectionIdentifier`, the way macOS 15's `-[Springboard init]` did.
    ///
    /// The initialiser's signature is in ``requiredMethods``, so this only runs on a Dock it matches.
    /// `DynamicObject` copies each argument's bytes as they are, so every one is the exact type its
    /// encoding names, and the frame, larger than three words, goes in an `NSValue`.
    static func makeLayerKitWindow(
        frame: CGRect,
        connectionIdentifier: UInt32,
        displayIdentifier: CGDirectDisplayID,
        tags: UInt64,
        level: Int32
    ) -> NSObject? {
        let window = ObjC.WALayerKitWindow(
            frame: NSValue(rect: frame),
            connection: connectionIdentifier,
            display: displayIdentifier,
            tags: tags,
            level: level
        ).asObject
        guard let window else {
            #log(.error, "WALayerKitWindow could not be made")
            return nil
        }
        return window
    }
}
